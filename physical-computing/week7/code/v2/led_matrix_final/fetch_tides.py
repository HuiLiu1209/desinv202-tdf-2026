#!/usr/bin/env python3
"""Download NOAA SF tides before uploading; no Wi-Fi is needed on the ESP32."""

import argparse
import json
import math
from datetime import date, datetime, timedelta
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import urlopen
from zoneinfo import ZoneInfo

ENDPOINT = "https://api.tidesandcurrents.noaa.gov/api/prod/datagetter"
DAYS = 64
SAMPLES = 96


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--end-date", type=date.fromisoformat,
                        default=datetime.now(ZoneInfo("America/Los_Angeles")).date() - timedelta(days=1),
                        help="Last complete local date, YYYY-MM-DD (default: SF yesterday)")
    args = parser.parse_args()
    start = args.end_date - timedelta(days=DAYS - 1)
    params = dict(begin_date=start.strftime("%Y%m%d"),
                  end_date=args.end_date.strftime("%Y%m%d"),
                  station="9414290", product="predictions", datum="MLLW",
                  time_zone="lst_ldt", interval="15", units="metric",
                  application="HuiAmbientDisplay", format="json")
    url = ENDPOINT + "?" + urlencode(params)
    print(f"Fetching {start} through {args.end_date}, San Francisco local time...")
    with urlopen(url, timeout=60) as response:
        payload = json.load(response)
    if "error" in payload:
        raise ValueError(payload["error"])
    predictions = payload.get("predictions", [])
    if len(predictions) != DAYS * SAMPLES:
        raise ValueError(f"Expected {DAYS * SAMPLES} points, got {len(predictions)}. "
                         "Check missing samples or a daylight-saving transition; no data was overwritten.")

    # Require 96 consecutive fifteen-minute timestamps for each local date.
    rows = []
    for day in range(DAYS):
        local_date = start + timedelta(days=day)
        values = []
        for sample in range(SAMPLES):
            point = predictions[day * SAMPLES + sample]
            expected = datetime.combine(local_date, datetime.min.time()) + timedelta(minutes=15 * sample)
            if point.get("t") != expected.strftime("%Y-%m-%d %H:%M"):
                raise ValueError(f"Unexpected timestamp: {point.get('t')}, expected {expected}")
            value = float(point["v"])
            if not math.isfinite(value):
                raise ValueError(f"Invalid tide height at {expected}")
            height_mm = round(value * 1000)
            if not -32768 <= height_mm <= 32767:
                raise ValueError(f"Tide height cannot fit int16_t at {expected}")
            values.append(height_mm)
        rows.append(values)

    low = min(map(min, rows))
    high = max(map(max, rows))
    if high <= low:
        raise ValueError("Tide range must be positive")
    lines = ["// Generated by fetch_tides.py; NOAA historical-date predictions, not observations.",
             "#pragma once", "#include <Arduino.h>",
             f'constexpr char TIDE_START_DATE[] = "{start}";',
             f'constexpr char TIDE_END_DATE[] = "{args.end_date}";',
             f"constexpr uint8_t TIDE_DAYS = {DAYS};",
             f"constexpr uint8_t TIDE_SAMPLES_PER_DAY = {SAMPLES};",
             f"constexpr int16_t TIDE_MIN_MM = {low};",
             f"constexpr int16_t TIDE_MAX_MM = {high};",
             "const int16_t TIDE_MM[TIDE_DAYS][TIDE_SAMPLES_PER_DAY] PROGMEM = {"]
    for day, values in enumerate(rows):
        lines.append(f"  // {start + timedelta(days=day)}")
        lines.append("  {" + ", ".join(map(str, values)) + "},")
    lines.append("};\n")
    root = Path(__file__).resolve().parent
    # Archive the API response and request parameters for reproducibility.
    archive = dict(source_url=url, station="9414290", product="predictions",
                   time_zone="lst_ldt", units="metric", datum="MLLW",
                   start_date=str(start), end_date=str(args.end_date), response=payload)
    (root / "noaa_tides.json").write_text(json.dumps(archive, indent=2) + "\n")
    (root / "tide_data.h").write_text("\n".join(lines))
    print(f"Saved {len(rows)} days x {SAMPLES} samples = {len(predictions)} verified timestamps.")
    print(f"Tide range: {low / 1000:.3f} to {high / 1000:.3f} m MLLW")


if __name__ == "__main__":
    main()
